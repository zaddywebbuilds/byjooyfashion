$items = @()
foreach ($slug in $meta.Keys) {
  $dir = Join-Path $imgRoot $slug
  if (!(Test-Path $dir)) { Write-Warning "missing: $slug"; continue }
  $files = Get-ChildItem $dir -File |
           Sort-Object { [int]($_.BaseName -replace '.*-(\d+)$','$1') } |
           ForEach-Object { $_.Name }
  $m = $meta[$slug]
  $items += [pscustomobject]@{
    slug      = $slug
    name      = $m.name
    tag       = $m.tag
    priceLow  = $m.priceLow
    priceHigh = $m.priceHigh
    sizes     = $m.sizes
    note      = $m.note
    images    = @($files)
  }
}

$json = $items | ConvertTo-Json -Depth 5
$utf8 = New-Object System.Text.UTF8Encoding $false

# data/products.json is the live catalogue. The Studio dashboard rewrites this
# file, and the site fetches it at runtime.
$jsonPath = Join-Path $base "data\products.json"
New-Item -ItemType Directory -Force (Split-Path $jsonPath) | Out-Null
[System.IO.File]::WriteAllText($jsonPath, $json, $utf8)

# products.js is the baked fallback, used if that fetch ever fails.
$js = "// Auto-generated by build-data.ps1 - do not edit by hand.`nwindow.BYJOOY_PRODUCTS = $json;`n"
$jsPath = Join-Path $base "assets\js\products.js"
[System.IO.File]::WriteAllText($jsPath, $js, $utf8)

Write-Host "Wrote $jsonPath"
Write-Host "Wrote $jsPath"
Write-Host "$($items.Count) styles, $(($items | ForEach-Object { $_.images.Count } | Measure-Object -Sum).Sum) images"
